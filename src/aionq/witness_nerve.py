"""The witness relation as a nerve, and the one theorem it makes checkable.

Round QSigma-R4 modelled witnessing as a single edge: one producer, one verifier,
one mode.  That is enough for two parties and wrong for three, because with three
the interesting object is not any party but the *shape* of who checked whom.

    parties          -> vertices
    verification acts -> directed edges, each carrying a mode
    evidence          -> a property of the GRAPH, not of any vertex

This is the same nerve the rest of this repository measures, and it inherits the
same failure mode.  In S3-S6 a cycle in a nerve could carry holonomy that no
single edge revealed.  Here a cycle carries something worse: nothing at all,
while looking like everything.

The attestation cycle
---------------------
Let A attest to B's claim, B attest to C's, and C attest to A's.  Every party is
now verified by a party that is not itself.  Every ``producer != verifier`` check
passes.  And no one has computed anything: the loop is a closed system of
signatures with no external contact.

    A --attested--> B --attested--> C --attested--> A

If the evidence measure rises when this cycle is added, the measure is circular
and can be inflated for free by adding parties.  That is the whole content of the
theorem below, and it is why R4's ``independent`` was defined by RECOMPUTATION
rather than by "a different name in the verifier field".

    THEOREM (attestation cycles cannot manufacture independence).
    Let G be a witness graph and C an attestation cycle on the same claim.  Then

        evidence_rank(G + C) = max(evidence_rank(G), ATTESTED).

    In particular no number of attestation cycles reaches REVIEWED or
    INDEPENDENT, and beyond the first attestation they add exactly nothing.

    PROOF.  evidence_rank is a max over per-act ranks.  Every edge of C has mode
    `attested` and, being a cycle, has producer != verifier at each edge, so each
    contributes exactly ATTESTED.  A max with constants equal to ATTESTED is
    max(existing, ATTESTED).  []

    FIRST STATED WRONGLY, and the test caught it.  The original claim here was
    the stronger `evidence_rank(G) = evidence_rank(G - C)` -- attestation cycles
    are *inert*.  That is false: when the cycle is the only support, removing it
    drops the rank from ATTESTED to NONE, and the suite reported `assert 0 == 1`
    within a minute of the theorem being written.  An attestation is not nothing;
    it is bounded.  The corrected statement is the one that matters anyway, since
    the risk was never that signatures count for something -- it is that enough
    of them might add up to a measurement.

This is the discrete, finite shadow of the Payor / Loeb situation: `[]([]P -> P)
-> []P` fails when the boxes belong to different parties who only ever quote each
other.  The repository makes no claim about the modal statement; it implements
and tests the finite one.

Orbit language, since the archive's is the useful export here: the evidence
measure must be *orbit-collapsed* under the group generated by inserting and
deleting attestation cycles.  A measure that varies over that orbit is reporting
the social graph, not the evidence.
"""

from __future__ import annotations

from dataclasses import dataclass, field

__all__ = ["WitnessAct", "WitnessGraph", "EvidenceRank", "MODE_RANK",
           "attestation_cycles", "evidence_rank"]


#: How much evidence a single act can transmit.  Strictly ordered, and the order
#: is the claim: an attestation is above nothing and below a recomputation.
MODE_RANK = {
    "declined": 0,
    "pending": 0,
    "not_requested": 0,
    "contradicted": 0,      # informative, but transmits no SUPPORT
    "attested": 1,
    "reviewed": 2,          # can disagree while the arithmetic is right
    "recomputed": 3,        # the only mode that is a second computation
}


class EvidenceRank:
    NONE = 0
    ATTESTED = 1
    REVIEWED = 2
    INDEPENDENT = 3


@dataclass(frozen=True)
class WitnessAct:
    """`verifier` checked `claim`, which `producer` made, in this `mode`."""

    claim_id: str
    producer: str
    verifier: str
    mode: str

    def __post_init__(self) -> None:
        if self.mode not in MODE_RANK:
            raise ValueError(f"unknown witness mode {self.mode!r}")

    @property
    def rank(self) -> int:
        # A party verifying its own claim transmits nothing, whatever it did.
        # This is R4's `producer == verifier` rule, restated as a graph property
        # so that it composes: a self-loop cannot become evidence by being part
        # of a longer path.
        return 0 if self.verifier == self.producer else MODE_RANK[self.mode]


@dataclass
class WitnessGraph:
    """Parties and the acts between them.  Evidence lives here, not in a field."""

    acts: list = field(default_factory=list)

    def add(self, act: WitnessAct) -> "WitnessGraph":
        self.acts.append(act)
        return self

    @property
    def parties(self) -> set:
        out: set = set()
        for a in self.acts:
            out.add(a.producer)
            out.add(a.verifier)
        return out

    def edges(self) -> list:
        """(producer, verifier, mode) triples, for cycle detection."""
        return [(a.producer, a.verifier, a.mode) for a in self.acts]

    def without(self, drop) -> "WitnessGraph":
        drop = set(drop)
        return WitnessGraph([a for a in self.acts if a not in drop])


def attestation_cycles(graph: WitnessGraph) -> list:
    """Every directed cycle whose edges are ALL attestations.

    Depth-first, returning each cycle once as a tuple of acts.  Exponential in
    the worst case and irrelevant at the sizes this is used on -- a witness graph
    with enough parties for that to matter has a different problem.
    """
    by_source: dict = {}
    for act in graph.acts:
        if act.mode == "attested":
            by_source.setdefault(act.producer, []).append(act)

    found: list = []
    seen: set = set()

    def walk(start, node, path):
        for act in by_source.get(node, ()):
            if act.verifier == start:
                key = frozenset(path + [act])
                if key not in seen:
                    seen.add(key)
                    found.append(tuple(path + [act]))
            elif act.verifier not in {p.producer for p in path} | {start}:
                walk(start, act.verifier, path + [act])

    for party in sorted(graph.parties):
        walk(party, party, [])
    return found


def evidence_rank(graph: WitnessGraph, claim_id: str) -> int:
    """The best evidence any single act supplies for `claim_id`.

    Deliberately a MAX over acts and not a sum, and not a path composition.
    Summing would let ten attestations outweigh one recomputation, which is the
    arithmetic version of a mob outvoting a measurement.  Composition along paths
    would let evidence flow through parties that never touched the claim.

    Both alternatives were considered and rejected here rather than discovered
    later: each of them makes the attestation cycle profitable, which is exactly
    what the theorem in the module docstring forbids.
    """
    ranks = [a.rank for a in graph.acts if a.claim_id == claim_id]
    return max(ranks) if ranks else EvidenceRank.NONE


def is_independent(graph: WitnessGraph, claim_id: str) -> bool:
    return evidence_rank(graph, claim_id) >= EvidenceRank.INDEPENDENT
