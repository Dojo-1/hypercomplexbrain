"""Stirring the Majorana network: where a spectral multiplier moves you.

`qffo` established what a quantum-fractal-fractional operator *is*: a
coefficient multiplier, hence a function of the number operator, hence a
spectral band weight.  `majorana` established what the free-fermion class *is*:
the unitaries whose conjugation keeps the Majorana modes in their own span, a
subgroup of dimension ``C(2n,2) + 1`` inside ``4^n``.

Put the first on the second and there are two places to apply it, which sound
alike and are opposite.

**Single-particle.**  A Gaussian unitary is ``exp(iH)`` with
``H = (i/4) sum A_jk c_j c_k`` for real antisymmetric ``A``.  Weight the spectrum
of ``A`` -- the single-particle spectrum -- and the result is another real
antisymmetric matrix, so the result is another Gaussian unitary.  Exactly.  The
excitation is transport **along the fiber**, and it can be large: measured
displacement ``|A' - A| / |A|`` up to 0.40 with the free-fermion defect never
leaving 4e-15.

**Many-body.**  Weight the spectrum of ``H`` itself and quadraticity is not
preserved.  The result leaves the class, by an amount that grows with the
displacement: defect 1.02 at displacement 0.20, 3.27 at 0.47.

The comparison at matched displacement is the whole content:

    branch        displacement   free-fermion defect
    single-particle    0.1796    2.9e-15
    many-body          0.1986    1.02

Nearly the same distance travelled, fifteen orders of magnitude apart in whether
the certificate survives.  So a QFFO is a knob with two settings, and ``q``
controls how hard it is turned: at ``q = 0.5`` the many-body branch lands at
defect 1.0, at ``q = 0.9`` at 3.3.

WHY THIS IS THE USEFUL SHAPE.  The strategy portfolio's problem, recorded across
R1B and R1C, is that it has no graded transverse direction -- `matchgate_plan`
certifies or refuses, and the only thing the frame group moves is routing.  The
many-body branch here is a **parameterised, invariantly-measured departure** from
the certified class, generated by an operator with a fractal order rather than by
a random perturbation.  It supplies the transverse motion the portfolio lacks.
The single-particle branch supplies the complementary thing: a way to stir the
network hard while staying provably simulable, which is what an ablation control
needs.

A CORRECTION THIS MODULE EARNED BEFORE IT EXISTED.  The first version of the
measurement built its generator as ``sum A_jk c_j c_k`` and Hermitised.  For
``j != k`` the product ``c_j c_k`` is ANTI-Hermitian, so Hermitising annihilated
it: every Hamiltonian was zero, every unitary was the identity, and both branches
reported free-fermion defect ``0.000e+00``.  A dichotomy was very nearly recorded
from a measurement of the identity operator.  The factor of ``i`` is the whole
difference and `quadratic_hamiltonian` carries it.
"""

from __future__ import annotations

import numpy as np

__all__ = [
    "random_generator",
    "quadratic_hamiltonian",
    "gaussian_unitary",
    "excite_single_particle",
    "excite_many_body",
    "excitation_report",
]


def random_generator(modes: int, seed: int = 4) -> np.ndarray:
    """A real antisymmetric ``2n x 2n``: an element of ``so(2n)``."""
    rng = np.random.default_rng(seed)
    raw = rng.normal(size=(modes, modes))
    return (raw - raw.T) / 2.0


def quadratic_hamiltonian(generator, operators) -> np.ndarray:
    """``H = (i/4) sum_{j<k} A_jk c_j c_k``, Hermitian for real antisymmetric ``A``.

    The factor of ``i`` is load-bearing and is not decoration.  For ``j != k`` the
    Majorana product ``c_j c_k`` satisfies ``(c_j c_k)* = c_k c_j = -c_j c_k``: it
    is anti-Hermitian.  Multiplying by ``i`` makes it Hermitian; omitting the
    ``i`` and then symmetrising gives identically zero, which is how the first
    version of this measurement came to evaluate the identity operator and report
    a result about it.
    """
    generator = np.asarray(generator)
    size = len(operators)
    total = sum(1j * generator[left, right] * (operators[left] @ operators[right])
                for left in range(size) for right in range(size) if left < right)
    return (total + total.conj().T) / 2.0


def gaussian_unitary(generator, operators) -> np.ndarray:
    """``exp(iH)`` for the quadratic ``H``: an element of the free-fermion group."""
    from scipy.linalg import expm

    return expm(1j * quadratic_hamiltonian(generator, operators))


def excite_single_particle(generator, weights) -> np.ndarray:
    """Reweight the single-particle spectrum. The result is still in ``so(2n)``.

    ``iA`` is Hermitian, so it has a real spectrum and a unitary eigenbasis.
    Reweighting the eigenvalues and mapping back gives another real antisymmetric
    matrix, hence another Gaussian unitary -- containment is structural, not
    approximate, and holds for any weight sequence whatever.
    """
    generator = np.asarray(generator)
    spectrum, basis = np.linalg.eigh(1j * generator)
    moved = (basis @ np.diag(np.asarray(weights) * spectrum) @ basis.conj().T) / 1j
    moved = np.real(moved)
    return (moved - moved.T) / 2.0


def excite_many_body(hamiltonian, weights) -> np.ndarray:
    """Reweight the many-body spectrum. Quadraticity is not preserved.

    The eigenbasis of ``H`` is a many-body basis, and rescaling its eigenvalues
    independently produces an operator with support on Majorana words of degree
    higher than two.  That is the point: this is the branch that leaves the
    class, and the amount by which it leaves is what `excitation_report` measures.
    """
    hamiltonian = np.asarray(hamiltonian)
    spectrum, basis = np.linalg.eigh(hamiltonian)
    return basis @ np.diag(np.asarray(weights) * spectrum) @ basis.conj().T


def excitation_report(qubits: int = 3, kind: str = "caputo", sigma: float = 0.4,
                      varsigma: float = 0.3, q: float = 0.5,
                      seed: int = 4) -> dict:
    """Both branches, with the displacement each one travels.

    Reporting the displacement alongside the defect is what makes the comparison
    mean anything: a branch that stayed on the class by not moving would be a
    trivial result, and the single-particle branch moves as far as the many-body
    one and stays anyway.
    """
    from scipy.linalg import expm

    from .majorana import gaussian_defect, majorana_operators
    from .qffo import MultiplierReading

    operators = majorana_operators(qubits)
    modes = 2 * qubits
    generator = random_generator(modes, seed)
    hamiltonian = quadratic_hamiltonian(generator, operators)
    reading = MultiplierReading(kind, sigma, varsigma, q)

    single_weights = np.array([reading.weight(index + 2) for index in range(modes)])
    moved_generator = excite_single_particle(generator, single_weights)
    single_unitary = gaussian_unitary(moved_generator, operators)

    many_weights = np.array([reading.weight(index + 2)
                             for index in range(hamiltonian.shape[0])])
    moved_hamiltonian = excite_many_body(hamiltonian, many_weights)
    many_unitary = expm(1j * moved_hamiltonian)

    return {
        "qubits": qubits,
        "branch": kind,
        "q": q,
        "base_defect": gaussian_defect(gaussian_unitary(generator, operators),
                                       operators),
        "hamiltonian_norm": float(np.linalg.norm(hamiltonian, "fro")),
        "single_particle": {
            "displacement": float(np.linalg.norm(moved_generator - generator)
                                  / np.linalg.norm(generator)),
            "defect": gaussian_defect(single_unitary, operators),
        },
        "many_body": {
            "displacement": float(np.linalg.norm(moved_hamiltonian - hamiltonian)
                                  / np.linalg.norm(hamiltonian)),
            "defect": gaussian_defect(many_unitary, operators),
        },
    }
