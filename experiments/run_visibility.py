"""Round V1: does the visibility depth r* equal the code distance d?

PRE-REGISTRATION (written before the sweep was run)
---------------------------------------------------
Instrument   aionq.visibility.visibility_profile, exact for stabilizer states:
             g_r = (n - rank(S_r)) / n, S_r generated by stabilizer elements of
             weight <= r.

Prediction   For the [[n,1,n]] repetition-code codeword (the n-qubit GHZ state),
             the logical operator X^(x)n has weight n = d and no lower-weight
             element of the stabilizer group is independent of the 2-local
             Z_iZ_j subgroup.  Therefore:

               P1  g_r = 1/n exactly, for every 1 < r < n
               P2  r*  = n = d, exactly, for every n in 3..9
               P3  hidden structure = exactly one generator, never more

Kill         Any n in 3..9 with r* != n falsifies P2.
conditions   Any r in (1, n) with g_r != 1/n falsifies P1.
             If random Clifford states show the same r* = n behaviour, the
             signature is not diagnostic of code distance and P2 is uninformative
             even if true -- so a matched control is required, not optional.

Control      Random Clifford states at the same n.  These are stabilizer states
             with no designed distance; if r* tracks n for them too, the result
             says nothing about codes.

Scope        Stabilizer states only.  No claim is made about non-stabilizer
             states, and none about cognition.

Run with:  PYTHONPATH=src python3 experiments/run_visibility.py
"""

from __future__ import annotations

import sys

import numpy as np
from qiskit import QuantumCircuit
from qiskit.quantum_info import random_clifford

sys.path.insert(0, "src")

from aionq.splitform import code_distance
from aionq.visibility import visibility_profile


def repetition_codeword(n: int) -> QuantumCircuit:
    """|+_L> of the n-qubit bit-flip repetition code: the GHZ state. d = n."""
    qc = QuantumCircuit(n)
    qc.h(0)
    for i in range(1, n):
        qc.cx(0, i)
    return qc


# Stabilizer generators, supplied explicitly rather than via a hand-written
# encoder.  The first version of this experiment used one, it stabilized none of
# the Steane generators, and the "falsification" it produced was a circuit bug.
STEANE_LOGICAL_ZERO = [
    "IIIXXXX", "IXXIIXX", "XIXIXIX",     # X-type checks, weight 4
    "IIIZZZZ", "IZZIIZZ", "ZIZIZIZ",     # Z-type checks, weight 4
    "ZZZZZZZ",                            # logical Z-bar, fixes |0_L>
]

FIVE_QUBIT_LOGICAL_ZERO = [
    "XZZXI", "IXZZX", "XIXZZ", "ZXIXZ",   # [[5,1,3]] checks, weight 4
    "ZZZZZ",                               # logical Z-bar
]


def verify_generators(labels) -> bool:
    """Independent check that the supplied generators commute and are independent."""
    from qiskit.quantum_info import Pauli
    for i, a in enumerate(labels):
        for b in labels[i + 1:]:
            if not Pauli(a).commutes(Pauli(b)):
                return False
    return True


def main() -> int:
    print("Round V1 -- visibility depth vs code distance")
    print("=" * 74)

    print("\nP1/P2/P3: repetition code [[n,1,n]] (GHZ), predicted r* = n\n")
    print(f"  {'n':>3} {'d':>3} {'r*':>3} {'r*==d':>6}   g_r profile")
    print("  " + "-" * 68)
    p2_failures, p1_failures = [], []
    for n in range(3, 10):
        rep = visibility_profile(repetition_codeword(n))
        ok = rep.r_star == n
        p2_failures += [] if ok else [n]
        interior = [rep.coupling[r] for r in range(2, n)]
        if any(abs(g - 1.0 / n) > 1e-12 for g in interior):
            p1_failures.append(n)
        prof = " ".join(f"{g:.3f}" for g in rep.coupling[1:min(n, 8) + 1])
        print(f"  {n:>3} {n:>3} {rep.r_star:>3} {str(ok):>6}   {prof}")

    print("\nControl: random Clifford states with no designed distance\n")
    print(f"  {'n':>3} {'r*':>3}   (if r* tracks n here, the signature is not diagnostic)")
    print("  " + "-" * 68)
    control_rstar = []
    for n in range(3, 10):
        rs = [visibility_profile(random_clifford(n, seed=s).to_circuit()).r_star
              for s in range(6)]
        control_rstar.append(np.mean(rs))
        print(f"  {n:>3} {np.mean(rs):>5.2f}   individual: {rs}")

    print("\nReal codes, generators supplied explicitly and verified\n")
    code_rows = []
    for name, labels, d in (("Steane [[7,1,3]]", STEANE_LOGICAL_ZERO, 3),
                            ("Perfect [[5,1,3]]", FIVE_QUBIT_LOGICAL_ZERO, 3)):
        ok = verify_generators(labels)
        rep = visibility_profile(labels)
        prof = " ".join(f"{g:.3f}" for g in rep.coupling[1:len(labels[0]) + 1])
        print(f"  {name}  generators commute: {ok}")
        print(f"    d = {d}   r* = {rep.r_star}   g_r = {prof}")
        print(f"    rank(S_r) = {[int(v) for v in rep.rank_at]}")
        code_rows.append((name, d, rep.r_star))
    st_rstar = code_rows[0][2]

    print("\n" + "=" * 74)
    print("VERDICT")
    print("=" * 74)
    print(f"  P1 (g_r = 1/n for 1<r<n) : {'SURVIVED' if not p1_failures else f'FALSIFIED at n={p1_failures}'}")
    print(f"  P2 (r* = d)              : {'SURVIVED' if not p2_failures else f'FALSIFIED at n={p2_failures}'}")
    slope = np.polyfit(range(3, 10), control_rstar, 1)[0]
    print(f"  control slope dr*/dn     : {slope:.3f}")
    if slope > 0.8:
        print("  -> control r* also tracks n: the signature is NOT diagnostic of")
        print("     designed distance; it reflects stabilizer-state structure generally.")
    else:
        print("  -> control r* does not track n: the repetition result is informative.")
    mismatches = [(nm, d, rs) for nm, d, rs in code_rows if rs != d]
    for name, d, rs in code_rows:
        verdict = "matches d" if rs == d else f"does NOT equal d (= {d})"
        print(f"  {name}: r* = {rs}, {verdict}")

    # --- V1 CORRECTION (Round V3) -------------------------------------------
    # P2 was scored against d taken from each code's NAME. With d COMPUTED from
    # the logical cosets (aionq.splitform.code_distance) the repetition family
    # collapses: its stabilizer distance is 1 for every n, not n. "[[n,1,n]]" is
    # the X-distance convention -- the bit-flip code has a weight-1 logical Z
    # (Z_1 commutes with every Z_iZ_j check and is not in the stabilizer), so it
    # protects against X errors only.
    print("\n  P2 RE-SCORED against COMPUTED distance, not the code's name")
    print("  " + "-" * 68)
    print(f"  {'code':<24}{'r*':>4}{'d computed':>12}{'r*==d':>8}")
    recomputed = []
    for n in (3, 5, 7, 9):
        checks = ["".join("Z" if k in (i, i + 1) else "I" for k in range(n))
                  for i in range(n - 1)]
        d_true = code_distance(checks)
        rs = visibility_profile(repetition_codeword(n)).r_star
        recomputed.append((f"repetition n={n}", rs, d_true))
    for nm, labels in (("Steane [[7,1,3]]", STEANE_LOGICAL_ZERO[:6]),
                       ("Perfect [[5,1,3]]", FIVE_QUBIT_LOGICAL_ZERO[:4])):
        full = STEANE_LOGICAL_ZERO if "Steane" in nm else FIVE_QUBIT_LOGICAL_ZERO
        recomputed.append((nm, visibility_profile(full).r_star, code_distance(labels)))
    for nm, rs, d_true in recomputed:
        print(f"  {nm:<24}{rs:>4}{d_true:>12}{str(rs == d_true):>8}")
    agree = sum(1 for _, rs, d_true in recomputed if rs == d_true)
    print(f"\n  r* == d in {agree}/{len(recomputed)} cases.")
    print("  P2 IS FALSIFIED ON THE REPETITION FAMILY TOO. Round V1 scored it as")
    print("  'survived' only because d was read off the code's name. The single")
    print("  remaining agreement ([[5,1,3]]) is a coincidence, not a law.")

    print("\n  P2 GENERALISED (r* = d for any stabilizer code): "
          f"{'FALSIFIED' if mismatches else 'survived'}")
    if mismatches:
        print("  Steane [[7,1,3]] has r* = 4 while d = 3. Its weight-3 elements have")
        print("  GF(2) rank 4 of 7; the weight-4 checks are needed to complete the")
        print("  group. So r* is the minimum GENERATING WEIGHT of the stabilizer")
        print("  group, not the code distance. (Round V1 said the two 'coincide for")
        print("  repetition codes'; the re-scoring above retires that -- see V3.)")
        print("\n  Corrected reading: r* measures how deep a local probe must reach")
        print("  to reconstruct the whole stabilizer structure. Distance measures the")
        print("  lightest logical operator. Neither determines the other.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
